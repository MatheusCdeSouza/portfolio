function calcularIndicadores(registros, mes) {
  const contagens = { OK: 0, NOK: 0, 'ON HOLD': 0 };
  let semClassificacao = 0;

  for (const { data, situacao } of registros) {
    if (data.slice(0, 7) !== mes) continue;

    const situacaoNormalizada = situacao.trim().toUpperCase();
    const status = situacaoNormalizada === 'HOLD' ? 'ON HOLD' : situacaoNormalizada;
    if (Object.hasOwn(contagens, status)) {
      contagens[status] += 1;
    } else {
      semClassificacao += 1;
    }
  }

  const total = Object.values(contagens).reduce((soma, quantidade) => soma + quantidade, 0);
  return { contagens, total, semClassificacao };
}

const formatoPercentual = new Intl.NumberFormat('pt-BR', {
  style: 'percent',
  maximumFractionDigits: 1,
});

const filtroMensal = document.querySelector('#mes-reconferencia');
const cards = document.querySelectorAll('[data-situacao]');
const resumo = document.querySelector('#resumo-indicadores');

function atualizarIndicadores() {
  const { contagens, total, semClassificacao } = calcularIndicadores(amostra, filtroMensal.value);
  const percentuais = [];

  for (const card of cards) {
    const situacao = card.dataset.situacao;
    const quantidade = contagens[situacao];
    const percentual = total ? formatoPercentual.format(quantidade / total) : '—';
    card.querySelector('.percentual').textContent = percentual;
    card.querySelector('.contagem').textContent = `${quantidade} de ${total} registros classificados`;
    const rotulo = situacao === 'ON HOLD' ? 'ON HOLD (em espera)' : situacao;
    percentuais.push(`${rotulo} ${percentual}`);
  }

  const contagemSeparada = `Sem classificação: ${semClassificacao}`;
  resumo.textContent = total ? contagemSeparada : `Sem dados para calcular. ${contagemSeparada}`;

  const mes = filtroMensal.selectedOptions[0].textContent;
  const resultado = total ? percentuais.join(', ') + '. ' : '';
  document.querySelector('#anuncio-indicadores').textContent = `${mes}. ${resultado}${resumo.textContent}`;
}

const formatoMes = new Intl.DateTimeFormat('pt-BR', {
  month: 'long',
  year: 'numeric',
  timeZone: 'UTC',
});
const meses = amostra.map(({ data }) => data.slice(0, 7)).sort();
const mesAtual = new Date(meses[0] + '-01T00:00:00Z');
const ultimoMes = meses.at(-1);

while (mesAtual.toISOString().slice(0, 7) <= ultimoMes) {
  const valor = mesAtual.toISOString().slice(0, 7);
  const rotulo = formatoMes.format(mesAtual);
  filtroMensal.add(new Option(rotulo[0].toUpperCase() + rotulo.slice(1), valor));
  mesAtual.setUTCMonth(mesAtual.getUTCMonth() + 1);
}

filtroMensal.addEventListener('change', atualizarIndicadores);
atualizarIndicadores();

function prepararIndicadoresDeSituacao(seletor, registros, unidade) {
  const cards = [...document.querySelectorAll(seletor + ' [data-status-lista]')];
  for (const card of cards) {
    const quantidade = registros.filter(({ situacao }) => situacao === card.dataset.statusLista).length;
    card.querySelector('.percentual').textContent = formatoPercentual.format(quantidade / registros.length);
    card.querySelector('.contagem').textContent =
      quantidade.toLocaleString('pt-BR') + ' de ' + registros.length.toLocaleString('pt-BR') + ' ' + unidade;
  }

  return situacao => {
    for (const card of cards) {
      card.hidden = situacao !== '' && card.dataset.statusLista !== situacao;
    }
  };
}
